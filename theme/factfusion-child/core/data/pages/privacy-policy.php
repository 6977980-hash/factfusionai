<!-- wp:heading -->
<h2 class="wp-block-heading">What we handle, and why</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p><strong>Reading the site.</strong> Like every website, the servers of our hosting provider process your IP address and basic details of each request, such as the page asked for and your browser type. This is needed to deliver pages and keep the service secure.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Stopping abuse.</strong> To protect the fact generator, the fact widget and the public API, we count requests per visitor. We do this with a scrambled (salted and hashed) form of your IP address, not the address itself. These counters are deleted after about two days.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Reporting a problem with a fact.</strong> If you use the report form on a fact page, we store what you write and, if you choose to give it, your email address, so that the editor can review the report and ask you about it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Contacting us.</strong> A message sent through the contact form is delivered to the editor by email, with the name and email address you enter. It is not stored in the website's database.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We rely on our legitimate interest in running and securing the site for the items above, and on your consent for analytics.</p>

<h2 class="wp-block-heading">Why history myths last</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Looking at these cases together, a pattern appears. A myth usually survives for one of three reasons.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The first is that it is simpler. "Signed on July 4" is easier to remember than "approved on July 4, ordered onto parchment on July 19 and signed from August 2".</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The second is that it makes a better picture. A horned helmet, a lone rider at full gallop and a bell breaking as it rings for freedom are all more vivid than what the records show.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The third is that the true record has a gap. When nobody wrote down how the Liberty Bell cracked, a story grew to fill the silence.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->

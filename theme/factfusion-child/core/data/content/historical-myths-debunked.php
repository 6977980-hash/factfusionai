<p>Some of the best-known stories in history did not happen the way they are told. The seven myths on this page are each set against a primary source, or against the institution that holds the original document or object: the U.S. National Archives, the National Park Service sites that care for the Liberty Bell and the Pony Express trail, the National Museum of Denmark, the Paul Revere House, NASA and the text of a U.S. Supreme Court opinion. Every card links to the source so that you can read it yourself.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A note on the word "primary". A primary source is a record made at the time, such as the journal of the Continental Congress, or the thing itself, such as a helmet in a museum case. Most of us cannot handle those. What we can do is read what the people who hold them have published, and that is what each fact below was checked against.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Myth 1: The Declaration of Independence was signed on July 4, 1776</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>July 4 is the date the Declaration was approved. The signing came later, and the National Archives, which holds the document, quotes the journal of the Continental Congress for the date.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-declaration-of-independence-was-not-signed-on-july-4"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>The Archives calls the July 4 signing one of the most widely held misconceptions about the Declaration. A journal entry written at the time is a better witness than a tradition that grew up afterwards.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Myth 2: The Emancipation Proclamation freed all the slaves</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>It is often taught as the moment slavery ended in the United States. The National Archives, which holds the original, describes a document with far narrower reach.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-emancipation-proclamation-did-not-end-slavery-nationwide"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>None of this makes the proclamation unimportant. The Archives says it transformed the character of the war. It simply did not do what the short version of the story claims.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Myth 3: Vikings wore horned helmets</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The horned Viking is everywhere, from cartoons to costumes. The National Museum of Denmark points to the physical evidence, and there is very little of it.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-only-surviving-viking-helmet-has-no-horns"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>The museum adds two practical points: horns would get in the way in a fight and on a crowded ship, and no source from the period mentions them.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Myth 4: The crack in the Liberty Bell is where it broke</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Visitors look at the wide gap in the bell and see damage. The National Park Service, which cares for the bell, says they are looking at the repair.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-liberty-bells-famous-crack-is-actually-a-repair"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>The Park Service is also frank about what is not known. No one recorded when or why the bell first cracked. A myth often fills exactly that kind of gap in the record.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Myth 5: Paul Revere rode to Concord shouting his warning</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>In the popular version, Revere gallops all the way to Concord. The Paul Revere House, the museum in his former home, tells a messier story.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="paul-revere-was-captured-before-he-reached-concord"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>He did reach Lexington and deliver his warning. He was then stopped on the road, lost his horse, and walked back.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Myth 6: The Great Wall of China can be seen from the Moon</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>This one is about history's most famous wall but is really a claim about what the human eye can do. NASA says no.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-great-wall-of-china-is-not-visible-from-the-moon"]
<!-- /wp:html -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Myth 7: The Pony Express carried the mail for years</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Pony Express looms so large in stories of the American West that it is natural to assume it ran for a generation. The National Park Service, which manages the historic trail, gives its dates.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-pony-express-lasted-only-18-months"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>A telegraph line across the continent was authorized only about ten weeks after the riders set out.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">A bonus: the tomato in court</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Not every myth is about a date. People argue about whether a tomato is a fruit or a vegetable as if it were only a matter of botany. In the United States the question was once settled in court, and the opinion itself is the primary source.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-u-s-supreme-court-ruled-that-tomatoes-are-vegetables"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>The Court accepted the botany and ruled the other way anyway, because the law in question used the words as ordinary people use them.</p>

<h2 class="wp-block-heading">How these facts were checked</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Every fact above went through the same steps. An editor opened the NASA page, found the sentence that supports the claim, and wrote the claim so that it says no more than that sentence does. The source, its tier and the date of the check are recorded with the fact and shown on its page, together with a confidence score out of 100.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Three habits explain most of the differences between this list and the space facts you may have read elsewhere.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>First, we keep the source's units. If NASA gives both Fahrenheit and Celsius, so do we. If it gives only one, we do not convert it ourselves, because that would add a number the source never checked.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Second, we keep dates. Counts of moons change as discoveries are confirmed, so a count without a date goes out of date without anyone noticing.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Third, we leave things out. When a figure could not be confirmed, or two pages disagreed, the fact was written around the part that was certain. A shorter fact that is right is better than a longer one that might not be.</p>
<!-- /wp:paragraph -->


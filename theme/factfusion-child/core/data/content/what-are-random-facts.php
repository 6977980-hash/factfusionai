<h2 class="wp-block-heading">Five questions to ask of any random fact</h2>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Who says so? A named organization, document or study, or nobody in particular?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Can I open the source and read it myself?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Does the source say exactly this: the same number, the same unit, the same date?</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>When was it checked? A count of moons from ten years ago is a different fact today.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Which small words were dropped? Look for "about", "up to", "may", "at least" and "as of".</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>If you cannot answer the first two questions, treat the statement as a rumour. It may be interesting. It is not yet something to repeat as a fact.</p>
<!-- /wp:paragraph -->


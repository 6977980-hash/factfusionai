<!-- wp:heading -->
<h2 class="wp-block-heading">Verified facts keep their small words</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>There is a quieter difference between a checked fact and an unchecked one. Sources are careful, and a verified fact keeps that care. Look at the wording of these three.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="saturn-has-274-confirmed-moons-more-than-any-other-planet"]
<!-- /wp:html -->

<!-- wp:html -->
[factfusion_fact slug="bowhead-whales-may-live-for-more-than-200-years"]
<!-- /wp:html -->

<!-- wp:html -->
[factfusion_fact slug="the-greenland-shark-is-the-longest-lived-vertebrate-known"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>The first is tied to a date, because the count of moons keeps changing. The second says "may", because the source says the lifespan is unknown and only that the evidence points past 200 years. The third says "at least", because that is what the study measured. A trivia list would shorten them to "Saturn has 274 moons" and "bowhead whales live 200 years". The short versions are punchier. They are also less true.</p>
<!-- /wp:paragraph -->


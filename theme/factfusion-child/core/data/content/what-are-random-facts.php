<!-- wp:paragraph -->
<p>A random fact is a true statement that reaches you by chance, not because you asked a question. You did not go looking for the number of moons around Saturn. It simply turned up. "Random" describes how the fact was delivered. It says nothing about whether the fact is true. "Verified" is the other half of the picture: it describes what was done to the statement before it reached you. This article explains the difference, and how to tell which kind of fact you are reading.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Random is about delivery</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The pleasure of a random fact is that you did not need it. It arrives without a reason, and it is short enough to remember and repeat. A random fact generator turns that into a button: it holds a list of statements and shows you one of them by chance.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>That is all "random" means. The generator does not know whether its statements are true. It can only be as good as the list behind it. If the list was copied from another list, which was copied from a third, it is possible that nobody along the chain ever looked at a source. The fact still reads well. It may even be right. But you have no way of knowing.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Verified is about what happened before</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A verified fact has a history you can inspect. At the least, that means:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>a named source, not "scientists say";</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>a link, so that you can open the source yourself;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>the date the fact was checked, because sources change;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>the name of the person who checked it;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>wording that says no more than the source does.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>On this site every fact page shows those things, along with a tier from A to D for the kind of source and a confidence score out of 100. Our page <a href="{{verify_url}}">How we verify facts</a> describes the process step by step.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->

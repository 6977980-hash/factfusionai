<details class="wp-block-details ff-faq__item"><summary>How many oceans are there?</summary><!-- wp:paragraph -->
<p>One. NOAA says there is only one global ocean, divided into named regions. Most countries, including the United States, now recognize five: the Atlantic, Pacific, Indian, Arctic and Southern.</p>

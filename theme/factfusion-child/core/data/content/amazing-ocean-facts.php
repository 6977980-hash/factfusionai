<p>The Challenger Deep, in the Mariana Trench. NOAA gives its depth as approximately 10,935 meters, or 35,876 feet.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ff-faq__item"} -->
<details class="wp-block-details ff-faq__item"><summary>Is there really a waterfall under the ocean?</summary><!-- wp:paragraph -->
<p>Yes. NOAA says the world's largest waterfall lies beneath the Denmark Strait, between Iceland and Greenland, where cold, dense water sinks below warmer water and flows over a drop in the ocean floor.</p>
<!-- /wp:paragraph --></details>

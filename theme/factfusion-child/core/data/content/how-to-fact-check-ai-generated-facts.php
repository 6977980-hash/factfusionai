<!-- wp:heading -->
<h2 class="wp-block-heading">Step 5: Compare the wording exactly</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>This is where most errors show up. Put the claim next to the source and compare:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>the number and the unit;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>the date, including any "as of";</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>the scope: one country or the world, one species or all of them;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>the small words: "about", "up to", "may", "at least".</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>Two examples from our own collection show why this matters. The first keeps the date the source attached to its figure. The second corrects a date that many people hold with complete confidence.</p>
<!-- /wp:paragraph -->


<!-- wp:heading -->
<h2 class="wp-block-heading">Step 6: Look for a second source, and for conflicts</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>If your first source is not a primary one, find a second that is independent of it. Two websites that copied the same line do not count as two sources.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Expect to find disagreements. When we checked the size of the Pacific Ocean, two pages published by the same agency gave different areas: about 63 million square miles on one, about 59 million on the other. Our fact uses neither figure and keeps to what both pages agree on.</p>
<!-- /wp:paragraph -->

<!-- wp:html -->
[factfusion_fact slug="the-pacific-holds-more-than-half-of-earths-free-water"]
<!-- /wp:html -->

<!-- wp:paragraph -->
<p>The same thing happened with the giant Martian volcano Olympus Mons. The height on the source page did not match the figures given elsewhere, so our fact describes the size of the volcano's base and leaves the height out. A fact that says less but is certain is worth more than one that says more and might be wrong.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Step 7: Write down what you checked, and know when to stop</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Record the source, the address of the page and the date you read it. If you publish the fact, show them. Then other people can check you, which is the point.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>And if you cannot find a source after an honest search, stop. The claim is unconfirmed. Do not soften it, do not add "reportedly" and publish it anyway, and do not ask the AI whether it is sure. Leave it out.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">The patterns to watch for</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Check enough statements and the same kinds of error keep appearing:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>a famous myth, repeated because it appears in so much of what people have written;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>a correct number with the wrong unit, or a metric figure labelled as imperial;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>a figure that was right some years ago, such as a count of moons;</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>a hedge that has been removed, so that "may live over 200 years" becomes "lives 200 years";</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>a source that is real but does not contain the claim.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->


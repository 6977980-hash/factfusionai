<!-- wp:paragraph -->
<p>To fact-check a fact written by an AI tool, treat it as a lead, not as a source. Split it into single claims, find where each claim would have been recorded first, open that source yourself, and compare the wording number by number. If you cannot find a source, do not repeat the claim. The seven steps below are the method we use on this site before any fact is published. It works just as well for a sentence produced by a chatbot.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Why AI facts need checking</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>An AI language model produces text that sounds right. It is built to continue a passage in a plausible way, and it will give you a confident, well-formed sentence whether or not a source stands behind it. It may also offer a reference that does not exist, or one that exists but does not say what is claimed.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>None of that makes AI useless. It makes it a starting point. On this site AI helps to draft explanations and to organize content, but it is never the source of a fact, and every fact is checked by a person against its source before it is published.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Step 1: Treat the answer as a lead</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Read the AI's answer the way a reporter reads a tip. It tells you what to look for. It does not tell you that the thing is true. Nothing is settled until you have seen a source.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Step 2: Split it into single claims</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A sentence like "Saturn, the second largest planet, has 274 moons and rings 30 feet thick" contains several claims. Take them apart: the size ranking, the moon count, the thickness of the rings. Mark every number, unit, date, name and superlative such as "largest", "first" or "only". Those are the parts that can be wrong, and each needs its own check.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Step 3: Ask where it would be recorded first</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>For each claim, ask who would know first-hand. A planet's measurements come from the space agency that measured them. A historical date comes from the archive that holds the document. An animal's size comes from the body that studies the species. A new scientific finding comes from the published study. That is the primary source, and it is where you want to end up.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Step 4: Open the source yourself</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Do not ask the AI for a link and stop there. Go to the organization's own website, find the page, and read the sentence that supports the claim. If the AI gave you a link, open it and check that the page exists and that it says what the AI says it does.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->

<details class="wp-block-details ff-faq__item"><summary>Can I ask the AI to check its own facts?</summary><!-- wp:paragraph -->
<p>You can ask, but the answer is produced the same way as the first one, so it is not an independent check. Only a source you have opened yourself confirms a claim.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ff-faq__item"} -->
<details class="wp-block-details ff-faq__item"><summary>What counts as a primary source?</summary><!-- wp:paragraph -->
<p>The organization or document closest to the fact: the agency that made the measurement, the archive that holds the record, the published study, the text of a law or court opinion.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ff-faq__item"} -->
<details class="wp-block-details ff-faq__item"><summary>Is Wikipedia good enough?</summary><!-- wp:paragraph -->
<p>It is a useful map. Follow its footnotes to the source behind a statement and check that source. We rank cited encyclopedia articles as Tier B, below primary sources.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ff-faq__item"} -->
<details class="wp-block-details ff-faq__item"><summary>How long does it take to check one fact?</summary><!-- wp:paragraph -->
<p>For a simple claim with an official source, about ten to fifteen minutes. Claims that involve statistics, health or disputed history take longer and sometimes cannot be confirmed at all.</p>
<!-- /wp:paragraph --></details>

<h2 class="wp-block-heading">The claim</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>&ldquo;Mercury is the hottest planet because it is closest to the Sun.&rdquo;</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What the evidence shows</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Being closest to the Sun does not make Mercury the hottest planet. NASA states that despite its proximity to the Sun, Mercury is not the hottest planet. Mercury's day temperatures can reach about 800°F (430°C), but it has no real atmosphere, only a thin exosphere, so the heat escapes and night temperatures can drop to about -290°F (-180°C). Venus, the second planet from the Sun, is the hottest planet in the solar system. Its surface reaches about 872 degrees Fahrenheit (467 Celsius), hot enough to melt lead, because its thick atmosphere traps heat in a runaway greenhouse effect. NASA notes that Venus is hotter even than Mercury, the innermost planet.</p>
<!-- /wp:paragraph -->


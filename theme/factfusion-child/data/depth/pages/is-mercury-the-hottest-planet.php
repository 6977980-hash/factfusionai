<details class="wp-block-details"><summary>Why is Venus hotter than Mercury?</summary><!-- wp:paragraph -->
<p>NASA explains that Venus has a thick atmosphere that traps heat in a runaway greenhouse effect. Mercury has only a thin exosphere and cannot hold onto its heat.</p>

<h2 class="wp-block-heading">Why people believe it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>It seems reasonable to assume that the planet nearest the Sun would be the hottest, because distance from the Sun does affect how much sunlight a planet receives. The myth leaves out the role of a planet's atmosphere in holding heat.</p>
<!-- /wp:paragraph -->


<!-- wp:details -->
<details class="wp-block-details"><summary>How deep is the Mariana Trench?</summary><!-- wp:paragraph -->
<p>NOAA gives the Challenger Deep, in the Mariana Trench, a depth of about 10,935 meters (35,876 feet). A peer-reviewed sonar survey measured 10,924 meters, give or take 15.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How much does pressure increase in the ocean?</summary><!-- wp:paragraph -->
<p>NOAA says pressure rises by about one atmosphere for every 33 feet (10 meters) of depth.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How much of the deep sea has been explored?</summary><!-- wp:paragraph -->
<p>NOAA says explorers have seen less than 0.001 percent of the deep seafloor, an area about the size of Rhode Island.</p>
<!-- /wp:paragraph --></details>

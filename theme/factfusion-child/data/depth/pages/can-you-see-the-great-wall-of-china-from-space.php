<h2 class="wp-block-heading">Why people believe it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>NASA notes that the theory that the wall could be seen from the Moon dates back to at least 1938, and that the wall has frequently been billed as the only man-made object visible from space. Scientific American traces the idea to a 1932 Ripley's cartoon. The claim was repeated for decades before astronauts could check it.</p>
<!-- /wp:paragraph -->


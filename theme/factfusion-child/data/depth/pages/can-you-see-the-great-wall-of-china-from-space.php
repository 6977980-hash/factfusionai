<h2 class="wp-block-heading">The claim</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>&ldquo;You can see the Great Wall of China from space with the naked eye.&rdquo;</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What the evidence shows</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>NASA describes the idea that the Great Wall is visible from space as a myth. According to NASA, the wall is difficult or impossible to see from Earth orbit without the high-powered camera lenses astronauts use, and it is not visible from the Moon. One reason is that the wall is built from material of about the same color and texture as the land around it, so it does not stand out. NASA notes that it is questionable whether the wall can be seen with the unaided eye from space. The theory lost ground after China's own astronaut, Yang Liwei, said he could not see the structure. In November 2004, astronaut Leroy Chiao took what NASA calls the first confirmed photo of the wall from the International Space Station, using a camera rather than his eyes alone.</p>

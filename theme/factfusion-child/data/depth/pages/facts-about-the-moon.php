<!-- wp:details -->
<details class="wp-block-details"><summary>Is there a dark side of the Moon?</summary><!-- wp:paragraph -->
<p>Not really. The side we never see from Earth is the far side, and NASA says it gets just as much sunlight as the near side.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is the Moon getting farther away?</summary><!-- wp:paragraph -->
<p>Yes. NASA says it moves about an inch farther from Earth each year. JPL, using laser measurements, gives 1.5 inches (3.8 centimeters).</p>

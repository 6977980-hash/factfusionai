<h2 class="wp-block-heading">The claim</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>&ldquo;Lightning never strikes the same place twice.&rdquo;</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What the evidence shows</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Lightning can and often does strike the same place more than once. The National Weather Service says lightning often strikes the same place repeatedly, especially if it is a tall, pointy, isolated object. NOAA's National Severe Storms Laboratory notes that lightning does hit the same spot, or almost the same spot, more than once, and that lightning usually strikes the tallest object, because taller objects are more likely to produce the upward channel that connects with a strike. The Empire State Building is a well-known example: the National Weather Service puts it at an average of 23 strikes a year, and a NOAA article says about 25 times per year.</p>
<!-- /wp:paragraph -->


<h2 class="wp-block-heading">Why people believe it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>NOAA's National Severe Storms Laboratory calls repeat strikes "contrary to folk wisdom," which shows the saying is a long-standing piece of folklore rather than a scientific finding. It is often used as a figure of speech about unlikely events happening twice.</p>
<!-- /wp:paragraph -->


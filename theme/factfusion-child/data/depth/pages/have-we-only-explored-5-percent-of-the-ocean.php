<h2 class="wp-block-heading">The claim</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>&ldquo;We have explored only 5 percent of the ocean.&rdquo;</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What the evidence shows</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The answer depends on what counts as explored, and no single figure such as 5 percent captures it. NOAA Ocean Exploration reports that, as of April 2026, 28.7% of the global seafloor had been mapped with modern high-resolution technology, and about 56% of the seafloor beneath U.S. waters had been mapped to those standards. Seeing the seafloor directly is far rarer: NOAA says explorers have seen less than 0.001% of the deep ocean seafloor. This matters because more than 90% of the ocean is deep ocean, deeper than 200 meters (656 feet), and the ocean covers about 70% of Earth's surface. NOAA also notes that the ocean will never be fully explored.</p>
<!-- /wp:paragraph -->


<h2 class="wp-block-heading">Why people believe it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Percentages for ocean exploration change over time and depend on whether they describe mapping, direct observation or sampling, so older or loosely defined figures can keep circulating after newer data are published. A single short number is also easier to repeat than an explanation of how mapping and direct observation differ.</p>

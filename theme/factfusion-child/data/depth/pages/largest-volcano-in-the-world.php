<h2 class="wp-block-heading">Is Mauna Loa still active?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Yes. The USGS counts 34 eruptions since 1843, and the most recent began on November 27, 2022. It is a basalt shield volcano: a broad, gently sloping mountain built by many lava flows. The Hawaiian name Mauna Loa means &ldquo;Long Mountain,&rdquo; and the USGS notes that the part above water stretches about 120 km (74 miles).</p>

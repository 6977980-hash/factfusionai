<h2 class="wp-block-heading">How tall is Mauna Loa if you measure from the bottom?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Mauna Loa's summit is about 13,680 feet (4,169 meters) above sea level, which does not sound huge. Most of the volcano is hidden. The National Park Service says it rises about 30,000 feet from the bottom of the sea, a greater height than Mount Everest.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The USGS goes one step further. Its flanks drop about 5 km (16,400 ft) below sea level to the seafloor, and Mauna Loa's weight has pushed the seafloor down by another 8 km (26,200 ft). Counted from that sunken base, the summit is about 17 km (55,700 ft) up. The two figures are not in conflict: one stops at the seafloor, the other includes the dip the volcano's weight has made in it.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What is the largest volcano in the solar system?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Olympus Mons on Mars. NASA calls it the largest volcano in the solar system and compares its base to the size of the US state of Arizona. The European Space Agency, which photographed its summit crater from orbit, gives it an average elevation of 22 km, with a summit caldera about 3 km deep.</p>

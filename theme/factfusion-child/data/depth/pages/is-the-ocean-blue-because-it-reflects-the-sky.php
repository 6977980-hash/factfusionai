<h2 class="wp-block-heading">Why people believe it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Woods Hole Oceanographic Institution notes that one common idea is that the ocean reflects the sky. Because both the sky and the open ocean look blue on a clear day, it is easy to assume one causes the other.</p>
<!-- /wp:paragraph -->


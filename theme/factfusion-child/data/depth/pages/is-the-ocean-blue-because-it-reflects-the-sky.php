<h2 class="wp-block-heading">The claim</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>&ldquo;The ocean is blue because it reflects the sky.&rdquo;</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What the evidence shows</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Sky reflection plays a small part at the surface, but the main reason the ocean looks blue is the water itself. NOAA explains that water absorbs colors in the red part of the light spectrum and, like a filter, leaves behind colors in the blue part of the spectrum for us to see. The Woods Hole Oceanographic Institution adds that when light shines through water, colors with longer wavelengths are absorbed, while blue light can penetrate the deepest. Because this happens inside the water rather than on its surface, the blue color does not depend only on what the sky looks like overhead.</p>
<!-- /wp:paragraph -->


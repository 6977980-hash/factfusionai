<h2 class="wp-block-heading">The claim</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>&ldquo;There is a dark side of the Moon that never gets sunlight.&rdquo;</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What the evidence shows</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The Moon does have a side that is always hidden from Earth, but it is not permanently dark. NASA explains that the Moon is tidally locked: it takes almost the same amount of time to rotate once on its axis as it does to orbit Earth, so we always see the same face. The hidden half is more accurately called the far side. According to NASA, the side of the Moon we do not see from Earth gets just as much sunlight as the side we do see, and both sides of the Moon receive sunlight. The only dark side of the Moon at any moment is whichever half is pointed away from the Sun, which changes as the Moon turns.</p>
<!-- /wp:paragraph -->


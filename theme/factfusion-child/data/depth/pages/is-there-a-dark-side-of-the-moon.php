<h2 class="wp-block-heading">Why people believe it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>NASA explains that the phrase "dark side of the Moon" usually refers to the side we cannot see from Earth, so "dark" was used in the sense of unseen or unknown. NASA adds that it only seems that half of the Moon receives sunlight because Earth only views half of the Moon.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Questions and answers</h2>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Why do we always see the same side of the Moon?</summary><!-- wp:paragraph -->
<p>NASA explains that the Moon is tidally locked, so its spin matches its orbit and the Moon never turns its back to us. That is why the far side stays hidden from Earth.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What is the actual dark side of the Moon?</summary><!-- wp:paragraph -->
<p>According to NASA, the only dark side of the Moon is the side pointed away from the Sun at any given time. That half changes as the Moon rotates.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Does the far side of the Moon get sunlight?</summary><!-- wp:paragraph -->
<p>Yes. NASA states that the side we do not see from Earth gets just as much sunlight as the side we do see.</p>
<!-- /wp:paragraph --></details>

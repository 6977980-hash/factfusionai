<h2 class="wp-block-heading">Why did the can opener take so long?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Two reasons stand out. Early cans were too thick for a small hand tool, and they were rare: at a few an hour, cans were a niche item, with the Royal Navy among the first big buyers. Only when thinner steel cans arrived and canned food reached ordinary shops did a dedicated opener start to make sense.</p>

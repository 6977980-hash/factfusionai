<p>The tin can was patented in 1810 by Peter Durand of England. Canning itself is a year older: Nicolas Appert of France worked out how to preserve food in sealed, heated jars in 1809. The oddest part of the story came next. For almost 50 years there was no can opener, so people opened cans with a hammer and chisel.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Who invented canning?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Nicolas Appert of France, in 1809. Encyclopaedia Britannica says he developed the method after long research, answering his government's call for a way to keep food for the army and navy. Appert sealed food tightly in a bottle or jar, heated it, and kept it sealed until it was eaten. He used glass, not metal.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">When was the tin can invented?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>In 1810. Britannica says Peter Durand of England patented tin-coated iron cans that year in place of bottles, and that by 1820 he was supplying canned food to the Royal Navy in large quantities. Early cans were slow to make: Smithsonian magazine reports a rate of about six an hour, rising to sixty an hour by the 1840s.</p>
<!-- /wp:paragraph -->


<!-- wp:heading -->
<h2 class="wp-block-heading">How did people open cans before the can opener?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>With a hammer and chisel. The first cans were wrought iron lined with tin, and Smithsonian magazine, citing Connecticut History, says they could be as thick as 3/16 of an inch. A hammer and chisel was not just the home method. It was what the makers told you to use.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">When was the can opener invented?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Ezra J. Warner of the United States patented a can opener on January 5, 1858, when thinner steel cans were starting to replace iron ones. It was a blade with a guard that you sawed around the lid, leaving a jagged edge. The public never loved it, but it served the U.S. Army in the Civil War, and grocery clerks used it to open cans for customers.</p>
<!-- /wp:paragraph -->


<!-- wp:details -->
<details class="wp-block-details"><summary>How long is a day on Venus?</summary><!-- wp:paragraph -->
<p>One rotation of Venus takes 243 Earth days, according to NASA. One trip around the Sun takes 225 Earth days, so the day is longer than the year.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Why is Venus hotter than Mercury?</summary><!-- wp:paragraph -->
<p>NASA puts the surface of Venus at about 872 degrees Fahrenheit (467 Celsius), hot enough to melt lead. Its thick atmosphere traps heat, which is why it beats Mercury.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Does Venus have any moons?</summary><!-- wp:paragraph -->
<p>No. NASA says Mercury and Venus are the only planets in our solar system without moons.</p>

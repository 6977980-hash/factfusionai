<h2 class="wp-block-heading">How long is a day on Venus?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Venus turns very slowly. One full spin takes longer than one trip around the Sun, so a Venus day is longer than a Venus year.</p>
